import { Link } from "react-router-dom";
import { AlertTriangle, CalendarClock, Check, CheckSquare, ExternalLink, Eye, Facebook, Heart, Instagram, Loader2, MessageCircle, Pencil, RotateCcw, Send, Sparkles, Square, Undo2, X } from "lucide-react";
import ScaledPost from "./PostCanvas";
import { getTemplate } from "./templates";
import { fmtWhen, imageIsStale } from "./lib/publish";
import { PILLAR_LABEL, StatusBadge } from "./ui";

const n = (v) => (v == null ? "—" : Number(v).toLocaleString("en-US"));

function Act({ onClick, icon: I, children, tone = "", title, to }) {
  const cls = `inline-flex h-7 items-center gap-1 border px-2 text-[11.5px] font-medium transition-colors ${tone || "border-hair bg-card text-ink/70 hover:border-[#ff3c00] hover:text-[#ff3c00]"}`;
  if (to) return <Link to={to} className={cls} title={title}><I className="h-3 w-3" />{children}</Link>;
  return <button type="button" onClick={onClick} className={cls} title={title}><I className="h-3 w-3" />{children}</button>;
}
const FLAME = "border-[#ff3c00] bg-[#ff3c00] text-white hover:bg-ink hover:border-ink";

export function Metrics({ insights, compact }) {
  if (!insights) return null;
  const items = [[Heart, insights.likes, "Likes"], [MessageCircle, insights.comments, "Comments"], [Eye, insights.reach, "Reach"]];
  return (
    <div className={`flex items-center gap-3 font-mono tabular-nums text-ink/70 ${compact ? "text-[10.5px]" : "text-[11.5px]"}`}>
      {items.map(([I, v, l]) => <span key={l} className="inline-flex items-center gap-1" title={l}><I className="h-3 w-3 text-[#ff6a00]" />{n(v)}</span>)}
    </div>
  );
}

export default function PostCard({ post, tz, selected, onToggle, actions }) {
  const t = getTemplate(post.template);
  const s = post.status || "draft";
  const targets = post.publish_targets || {};
  const stale = s === "approved" && imageIsStale(post);
  return (
    <div className={`group relative flex flex-col border bg-card transition-colors ${selected ? "border-[#ff3c00]" : "border-hair hover:border-[#ff3c00]/50"}`}>
      <Link to={`/social/${post.id}`} className="block">
        <ScaledPost template={post.template} spec={post.spec} />
      </Link>
      {onToggle && (
        <button type="button" onClick={onToggle} className={`absolute left-1.5 top-1.5 bg-white/90 p-0.5 ${selected ? "text-[#ff3c00]" : "text-ink/40 opacity-0 group-hover:opacity-100"}`} title="Select">
          {selected ? <CheckSquare className="h-4 w-4" /> : <Square className="h-4 w-4" />}
        </button>
      )}
      {(s === "approved" || s === "publishing") && post.scheduled_at && (
        <div className="absolute right-1.5 top-1.5 flex items-center gap-1 bg-ink px-1.5 py-1 font-mono text-[10px] text-white">
          {s === "publishing" ? <Loader2 className="h-3 w-3 animate-spin" /> : <CalendarClock className="h-3 w-3 text-[#ff6a00]" />}{fmtWhen(post.scheduled_at, tz, { short: true })}
        </div>
      )}

      <div className="flex flex-1 flex-col px-3 py-2.5">
        <div className="flex items-center gap-1.5">
          <StatusBadge status={s} />
          {post.generated_by === "claude" && <Sparkles className="h-3 w-3 text-[#ff6a00]" title="Generated by Claude" />}
          {(s === "approved" || s === "posted") && (
            <span className="flex items-center gap-1 text-ink/40">
              {targets.instagram !== false && <Instagram className="h-3 w-3" />}
              {targets.facebook && <Facebook className="h-3 w-3" />}
            </span>
          )}
          <span className="mono-label ml-auto truncate text-[8.5px] text-ink/45">{PILLAR_LABEL[post.pillar] || ""}</span>
        </div>
        <Link to={`/social/${post.id}`} className="mt-1 block truncate text-[13px] font-medium hover:text-[#ff3c00]">{post.title || post.spec?.headline || "Untitled"}</Link>
        <p className="truncate text-[11px] text-ink/45">{t.label}{post.folder ? ` · ${post.folder}` : ""}{s === "draft" && post.planned_for ? ` · planned ${post.planned_for.slice(5).replace("-", "/")}` : ""}</p>

        {s === "posted" && (
          <div className="mt-2 space-y-1.5 border-t border-hair pt-2">
            <Metrics insights={post.insights} compact />
            <div className="flex flex-wrap items-center gap-2 text-[11px]">
              <span className="font-mono text-ink/45">{fmtWhen(post.published_at || post.posted_at, tz, { short: true })}</span>
              {post.ig_permalink && <a href={post.ig_permalink} target="_blank" rel="noreferrer" className="inline-flex items-center gap-0.5 text-[#ff3c00] hover:underline"><Instagram className="h-3 w-3" />View<ExternalLink className="h-2.5 w-2.5" /></a>}
              {post.fb_permalink && <a href={post.fb_permalink} target="_blank" rel="noreferrer" className="inline-flex items-center gap-0.5 text-[#ff3c00] hover:underline"><Facebook className="h-3 w-3" />View<ExternalLink className="h-2.5 w-2.5" /></a>}
            </div>
            {post.fb_error && <p className="line-clamp-2 text-[10.5px] text-[#c44a00]">Facebook: {post.fb_error}</p>}
          </div>
        )}
        {s === "failed" && post.publish_error && <p className="mt-2 line-clamp-3 border-l-2 border-[#b42318] pl-2 text-[11px] leading-snug text-[#b42318]">{post.publish_error}</p>}
        {s === "approved" && post.publish_error && <p className="mt-2 line-clamp-2 text-[10.5px] text-[#c44a00]">{post.publish_error}</p>}
        {stale && <p className="mt-2 flex items-start gap-1 text-[10.5px] leading-snug text-[#c44a00]"><AlertTriangle className="mt-px h-3 w-3 shrink-0" />Design changed since approval. Open it to re-render.</p>}
        {s === "declined" && <p className="mt-2 line-clamp-2 text-[11px] text-ink/50">{post.declined_reason ? `Declined: ${post.declined_reason}` : "Declined"}</p>}

        {actions && (
          <div className="mt-auto flex flex-wrap gap-1 pt-2.5">
            {s === "draft" && <>
              <Act onClick={() => actions.approve(post)} icon={Check} tone={FLAME}>Approve</Act>
              <Act onClick={() => actions.decline(post)} icon={X}>Decline</Act>
              <Act to={`/social/${post.id}`} icon={Pencil}>Edit</Act>
              <Act onClick={() => actions.postNow(post)} icon={Send} title="Approve and publish immediately">Post now</Act>
            </>}
            {s === "approved" && <>
              <Act onClick={() => actions.approve(post)} icon={CalendarClock}>Reschedule</Act>
              <Act onClick={() => actions.postNow(post)} icon={Send}>Post now</Act>
              <Act onClick={() => actions.unschedule(post)} icon={Undo2} title="Back to drafts">Unschedule</Act>
            </>}
            {s === "failed" && <>
              <Act onClick={() => actions.postNow(post)} icon={RotateCcw} tone={FLAME}>Retry now</Act>
              <Act onClick={() => actions.approve(post)} icon={CalendarClock}>Reschedule</Act>
              <Act onClick={() => actions.unschedule(post)} icon={Undo2}>To drafts</Act>
            </>}
            {s === "declined" && <Act onClick={() => actions.restore(post)} icon={Undo2}>Restore to drafts</Act>}
          </div>
        )}
      </div>
    </div>
  );
}
